const captionEnds = new Map(subtitles.map(s => [s.startMs, s.endMs / 1000]));
const spans: Record<Effect, number> = {indicate: .66, flash: .65, focus: .82, trace: .88, wiggle: .52};
export const narrationEvents = narrationClauses.flatMap(([captionStartMs, spokenReference, ...hits]) => hits.map(([start, targets, effect = 'indicate'], i) => ({
  captionStartMs, spokenReference, start, targets, effect,
  end: Math.min(start + spans[effect], captionEnds.get(captionStartMs)!, hits[i + 1]?.[0] ?? Infinity),
})));

export type Accent = {weight: number; progress: number; effect: Effect};
const smooth = (u: number) => { const x = Math.max(0, Math.min(1, u)); return x * x * (3 - 2 * x); };
export function narrationAt(t: number) {
  let lo = 0, hi = narrationEvents.length;
  while (lo < hi) {
    const mid = (lo + hi) >>> 1;
    if (narrationEvents[mid].start <= t) lo = mid + 1;
    else hi = mid;
  }
  const event = narrationEvents[lo - 1];
  if (!event || t >= event.end || t <= event.start) return undefined;
  const progress = (t - event.start) / (event.end - event.start);
  return {...event, progress, weight: smooth(progress / .35) * smooth((1 - progress) / .50)};
}
